const menu = ['김치찌개', '된장찌개', '비빔밥'];

const backup = menu;        // 개편 전 메뉴 백업

menu.push('냉면');           // 여름 신메뉴 추가
menu[0] = '김치찜';          // 김치찌개 → 김치찜으로 교체

console.log('개편 후 메뉴:', menu);
console.log('개편 전 백업:', backup);
