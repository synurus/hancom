function maskBadWord(comment) {
  comment.replace('바보', '**');
  return comment;
}

console.log(maskBadWord('이 바보야 답답하네'));   // 금칙어 포함 댓글
console.log(maskBadWord('오늘 영상 잘 봤어요'));  // 평범한 댓글
