const App = () => {
  let count = 0;                       // 화면에 보여 줄 숫자 — 그냥 변수다

  const click = () => {
    count++;                           // 값을 1 올린다
    console.log('변수 값:', count);     // 콘솔로 값을 확인해 본다
  };

  return <button onClick={click}>클릭 {count}</button>;
};

export default App;
